"""Build answer files from tools/answers.json.

Writes:
  app/js/answer-hashes.js  - salted SHA-256 hashes the app uses to check answers offline
  app/js/demo-answers.js   - plaintext answers, loaded only in demo mode (delete before deploying)
  supabase/seed.sql        - plaintext answers for the server's check function

Run from the project folder:  python3 tools/build_answers.py
"""
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def normalize(value: str) -> str:
    return re.sub(r"[^A-Z0-9]", "", str(value).upper())


def digest(salt: str, value: str) -> str:
    return hashlib.sha256(f"{salt}|{normalize(value)}".encode("utf-8")).hexdigest()


def main() -> int:
    key = json.loads((ROOT / "tools" / "answers.json").read_text(encoding="utf-8"))
    salt = key["salt"]

    hashes = {"kickoff": digest(salt, key["kickoff"]), "relays": {}}
    plain = {"kickoff": key["kickoff"], "relays": {}}
    for relay_id, item in key["relays"].items():
        hashes["relays"][relay_id] = {
            "main": digest(salt, item["main"]),
            "junior": digest(salt, item["junior"]) if item.get("junior") else None,
        }
        plain["relays"][relay_id] = {"main": item["main"], "junior": item.get("junior")}

    js = ROOT / "app" / "js"
    (js / "answer-hashes.js").write_text(
        "// Generated by tools/build_answers.py. Do not edit by hand.\n"
        f"window.ANSWER_SALT = {json.dumps(salt)};\n"
        f"window.ANSWER_HASHES = {json.dumps(hashes, indent=2)};\n",
        encoding="utf-8",
    )
    (js / "demo-answers.js").write_text(
        "// Generated by tools/build_answers.py. Demo mode only. Delete this file before deploying.\n"
        f"window.DEMO_ANSWERS = {json.dumps(plain, indent=2)};\n",
        encoding="utf-8",
    )

    rows = [f"  ('kickoff', 'main', '{normalize(key['kickoff'])}')"]
    for relay_id, item in key["relays"].items():
        rows.append(f"  ('{relay_id}', 'main', '{normalize(item['main'])}')")
        if item.get("junior"):
            rows.append(f"  ('{relay_id}', 'junior', '{normalize(item['junior'])}')")
    (ROOT / "supabase" / "seed.sql").write_text(
        "-- Generated by tools/build_answers.py. Run after schema.sql.\n"
        "delete from answers;\n"
        "insert into answers (relay_id, kind, answer_norm) values\n"
        + ",\n".join(rows)
        + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote hashes for {len(key['relays'])} relays plus the kickoff code.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
